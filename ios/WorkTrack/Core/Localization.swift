    /// dictionaries edited by hand, a string added to Dari and forgotten in
    /// Pashto shows the raw key on screen to exactly the users least likely to
    /// report it.
    static func keys(for language: Language) -> Set<String> {
        Set(dictionaries[language]?.keys ?? [:].keys)
